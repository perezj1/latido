import assert from 'node:assert/strict'
import { readFile,readdir } from 'node:fs/promises'
import { createSuizamenteDb,finishSzSession,szCorrectChoice,szRpc,SZ_ALICE,SZ_BOB,SZ_ADMIN } from './lib/suizamente-test-db.mjs'

let db
try {
  db=await createSuizamenteDb()
  const bank=JSON.parse(await readFile('supabase/seed-data/suizamente-questions.json','utf8'))
  assert.ok(bank.length>=200)
  assert.equal(new Set(bank.filter(q=>q.scope==='canton').map(q=>q.canton)).size,26)
  for(const category of ['administracion','vivienda','trabajo','salud','sociedad'])for(let level=1;level<=5;level++)assert.ok(bank.filter(q=>q.scope==='CH'&&q.category===category&&q.difficulty===level).length>=2)
  const guest=await szRpc(db,null,'summary')
  assert.equal(Object.keys(guest.coverage).length,26)
  assert.equal(guest.player,undefined)
  assert.ok(!JSON.stringify(guest).includes('correct_index'))
  const preview=await szRpc(db,SZ_ALICE,'summary')
  assert.equal(preview.player.level,1)
  assert.equal(preview.player.canton,'ZH','The initial learning canton comes from the actual user profile')
  assert.equal(preview.player.include_general,true)
  assert.equal(preview.player.include_canton,true)
  assert.equal((await szRpc(db,SZ_BOB,'summary')).player.canton,'BE','Each actor receives their own canton, not another account owner’s')
  assert.equal((await db.query('SELECT count(*)::integer n FROM suizamente_private.players')).rows[0].n,0,'Viewing a Home/Profile preview must not persist game data')
  await assert.rejects(szRpc(db,null,'start',{mode:'daily'}),/SZ_AUTH_REQUIRED/)
  await assert.rejects(szRpc(db,SZ_ALICE,'admin'),/SZ_FORBIDDEN/)
  for(const role of ['anon','authenticated'])await assert.rejects(db.transaction(async tx=>{await tx.exec(`SET LOCAL ROLE ${role}`);return tx.query('SELECT * FROM suizamente_private.versions')}),/permission denied/)
  console.log('Suizamente: private schema, anonymous boundary, admin authorization and content coverage passed.')

  let unknown=await szRpc(db,SZ_ADMIN,'start',{mode:'practice',category:'salud'})
  assert.equal(unknown.review_answers,null,'Solutions for a full route are not exposed before completion')
  const skippedVersion=unknown.question.version_id
  unknown=await szRpc(db,SZ_ADMIN,'answer',{session_id:unknown.id,position:0,choice:await szCorrectChoice(db,unknown),skip:true})
  assert.equal(unknown.answer.skipped,true)
  assert.equal(unknown.answer.choice,null)
  assert.equal(unknown.answer.correct,false,'No lo sé cannot be used to earn XP even when the supplied choice is correct')
  assert.equal(unknown.answer.xp,0)
  assert.equal(unknown.states[0],'skipped')
  const retryUnknown=await szRpc(db,SZ_ADMIN,'answer',{session_id:unknown.id,position:0,choice:unknown.answer.correct_option})
  assert.equal(retryUnknown.answer.skipped,true,'A skipped answer is also immutable')
  unknown=await finishSzSession(db,SZ_ADMIN,unknown)
  assert.equal(unknown.review_answers.length,5)
  assert.equal(unknown.review_answers[0].skipped,true)
  assert.ok(unknown.review_answers.every(a=>a.correct_answer&&a.explanation&&a.source_url))
  assert.equal((await szRpc(db,SZ_ADMIN,'summary')).stats.pending,1)
  const retryReview=await finishSzSession(db,SZ_ADMIN,await szRpc(db,SZ_ADMIN,'start',{mode:'review'}))
  assert.equal(retryReview.question.version_id,skippedVersion)
  assert.ok(retryReview.xp_gained>0,'Learning a previously skipped answer awards the first correct XP')
  assert.equal((await szRpc(db,SZ_ADMIN,'summary')).stats.pending,0)
  console.log('Suizamente: No lo sé persistence, no XP, immutable answers, private final review and later recovery passed.')

  await szRpc(db,SZ_ALICE,'preferences',{canton:'ZH',alias:'AnaZH',leaderboard_opt_in:true})
  await szRpc(db,SZ_BOB,'preferences',{canton:'BE',alias:'BrunoBE',leaderboard_opt_in:false})
  await assert.rejects(szRpc(db,SZ_BOB,'preferences',{canton:'GE',alias:'AnaZH'}),/duplicate key/)
  await assert.rejects(szRpc(db,SZ_BOB,'preferences',{canton:'XX',alias:'BrunoBE'}),/SZ_INVALID_CANTON/)
  await assert.rejects(szRpc(db,SZ_BOB,'preferences',{canton:'BE',alias:'private@example.com'}),/SZ_INVALID_ALIAS/)
  let daily=await szRpc(db,SZ_ALICE,'start',{mode:'daily',category:'idioma',level:5,xp:999999})
  assert.equal(daily.level,1,'Ignore client-supplied level/XP')
  assert.equal(daily.total,5)
  assert.equal(daily.answer,null)
  assert.equal(daily.question.correct_index,undefined)
  assert.equal(daily.question.explanation,undefined)
  await assert.rejects(szRpc(db,SZ_BOB,'session',{id:daily.id}),/SZ_SESSION_NOT_FOUND/)
  await assert.rejects(szRpc(db,SZ_BOB,'answer',{session_id:daily.id,position:0,choice:0}),/SZ_SESSION_NOT_FOUND/)
  assert.equal((await szRpc(db,SZ_ALICE,'session',{id:daily.id,advance:true})).position,0,'Cannot skip unanswered questions')
  const scopes=(await db.query('SELECT v.payload FROM suizamente_private.sessions s JOIN suizamente_private.versions v ON v.id=ANY(s.version_ids) WHERE s.id=$1',[daily.id])).rows.map(r=>r.payload)
  assert.equal(scopes.filter(q=>q.scope==='canton').length,2)
  assert.ok(scopes.every(q=>q.scope==='CH'||q.canton==='ZH'))
  assert.ok(scopes.every(q=>q.category!=='idioma'),'A crafted request cannot turn a daily route into optional language practice')
  const correct=await szCorrectChoice(db,daily)
  daily=await szRpc(db,SZ_ALICE,'answer',{session_id:daily.id,position:0,choice:(correct+1)%4})
  assert.equal(daily.answer.correct,false)
  assert.equal(daily.answer.xp,0)
  const duplicate=await szRpc(db,SZ_ALICE,'answer',{session_id:daily.id,position:0,choice:correct})
  assert.equal(duplicate.answer.correct,false,'Confirmed choice cannot be changed')
  daily=await finishSzSession(db,SZ_ALICE,daily)
  assert.equal(daily.correct_count,4)
  let summary=await szRpc(db,SZ_ALICE,'summary',{user_id:SZ_BOB})
  assert.equal(summary.player.user_id,SZ_ALICE)
  assert.equal(summary.stats.daily_completed,1)
  assert.equal(summary.stats.pending,1)
  assert.equal(summary.stats.first_correct,4)
  assert.equal(summary.stats.seen,5)
  const filtered=await szRpc(db,SZ_ALICE,'summary',{scope:'canton',level:5})
  assert.equal(filtered.stats.top_topic_correct,summary.stats.top_topic_correct,'Achievements do not change with category filters')
  const xpAfterDaily=summary.player.xp
  assert.equal((await szRpc(db,SZ_ALICE,'start',{mode:'daily'})).id,daily.id)
  await szRpc(db,SZ_ALICE,'answer',{session_id:daily.id,position:daily.position,choice:0})
  assert.equal((await szRpc(db,SZ_ALICE,'summary')).player.xp,xpAfterDaily)
  assert.equal((await db.query("SELECT count(*)::integer n FROM suizamente_private.rewards WHERE user_id=$1 AND award_key LIKE 'daily:%'",[SZ_ALICE])).rows[0].n,1)
  let review=await szRpc(db,SZ_ALICE,'start',{mode:'review'})
  assert.equal(review.total,1)
  review=await finishSzSession(db,SZ_ALICE,review)
  summary=await szRpc(db,SZ_ALICE,'summary')
  assert.equal(summary.stats.pending,0)
  assert.equal(summary.stats.first_correct,4,'Repaso does not rewrite the initial accuracy')
  assert.equal(summary.stats.ever_correct,5)
  assert.ok(review.xp_gained>0,'First correct answer after a mistake can grant XP')
  await assert.rejects(szRpc(db,SZ_ALICE,'start',{mode:'review'}),/SZ_NO_QUESTIONS/)
  await assert.rejects(szRpc(db,SZ_ALICE,'start',{mode:'ascent'}),/SZ_XP_REQUIRED/)
  console.log('Suizamente: ownership, daily scopes, resume, no skips, idempotency, XP ledger and review statistics passed.')

  const beforeLanguage=(await szRpc(db,SZ_BOB,'summary')).player.xp
  const language=await finishSzSession(db,SZ_BOB,await szRpc(db,SZ_BOB,'start',{mode:'practice',category:'idioma'}))
  assert.equal(language.xp_gained,0)
  assert.equal((await szRpc(db,SZ_BOB,'summary')).player.xp,beforeLanguage)
  const weekA=await szRpc(db,SZ_ALICE,'start',{mode:'weekly'}),weekB=await szRpc(db,SZ_BOB,'start',{mode:'weekly'})
  const weekRows=(await db.query('SELECT version_ids FROM suizamente_private.sessions WHERE id IN ($1,$2) ORDER BY id',[weekA.id,weekB.id])).rows
  assert.deepEqual(weekRows[0].version_ids,weekRows[1].version_ids)
  assert.equal(weekA.total,10)
  const xpBeforeWeekly=(await szRpc(db,SZ_ALICE,'summary')).player.xp
  await finishSzSession(db,SZ_ALICE,weekA)
  await finishSzSession(db,SZ_BOB,weekB)
  assert.equal((await szRpc(db,SZ_ALICE,'summary')).player.xp,xpBeforeWeekly)
  let board=await szRpc(db,null,'leaderboard')
  assert.equal(board.rows.length,1)
  assert.equal(board.rows[0].score,100)
  assert.equal(board.rows[0].alias,'AnaZH')
  assert.equal(board.mine,null)
  assert.ok(!JSON.stringify(board).includes(SZ_ALICE))
  await szRpc(db,SZ_BOB,'preferences',{canton:'BE',alias:'BrunoBE',leaderboard_opt_in:true})
  board=await szRpc(db,SZ_BOB,'leaderboard')
  assert.equal(board.rows.length,2)
  assert.ok(board.rows.every(row=>row.position===1),'Equal results share a position')
  assert.equal(board.mine.score,100)
  const weekVersion=(await db.query('SELECT version_ids[1] id FROM suizamente_private.sessions WHERE id=$1',[weekA.id])).rows[0].id
  await szRpc(db,SZ_ADMIN,'admin',{operation:'annul',version_id:weekVersion})
  board=await szRpc(db,null,'leaderboard')
  assert.ok(board.rows.every(row=>row.maximum===90&&row.score===90),'Annulling a question applies equally to all rankings')
  const revisedWeek=await szRpc(db,SZ_ALICE,'session',{id:weekA.id})
  assert.equal(revisedWeek.correct_count,9)
  assert.equal(revisedWeek.annulled_count,1)
  console.log('Suizamente: optional language, shared weekly challenge, opt-in aliases, ties and ranking annulment passed.')

  await db.query('UPDATE suizamente_private.players SET xp=150 WHERE user_id=$1',[SZ_ALICE])
  let ascent=await szRpc(db,SZ_ALICE,'start',{mode:'ascent'})
  ascent=await finishSzSession(db,SZ_ALICE,ascent,{wrongAt:[0,1]})
  assert.equal(ascent.correct_count,8)
  assert.equal(ascent.ascent_passed,false,'8/10 alone is insufficient if one category has no correct response')
  assert.equal((await szRpc(db,SZ_ALICE,'summary')).player.level,1)
  assert.equal((await szRpc(db,SZ_ALICE,'start',{mode:'ascent'})).id,ascent.id,'One ascent attempt each Zurich day')
  for(let level=1;level<=5;level++){
    await db.query("UPDATE suizamente_private.sessions SET day_key=date '2000-01-01'+$1::integer WHERE id=$2",[level,ascent.id])
    await db.query('UPDATE suizamente_private.players SET xp=$1 WHERE user_id=$2',[[150,400,800,1300,2000][level-1],SZ_ALICE])
    ascent=await finishSzSession(db,SZ_ALICE,await szRpc(db,SZ_ALICE,'start',{mode:'ascent'}))
    assert.equal(ascent.ascent_passed,true)
    const p=(await szRpc(db,SZ_ALICE,'summary')).player
    assert.equal(p.level,Math.min(5,level+1))
    assert.equal(p.route_completed,level===5)
  }
  await db.query("UPDATE suizamente_private.sessions SET day_key=date '2000-02-01' WHERE id=$1",[daily.id])
  await szRpc(db,SZ_ALICE,'preferences',{canton:'AG',alias:'AnaZH',leaderboard_opt_in:true})
  const advanced=await szRpc(db,SZ_ALICE,'start',{mode:'daily'})
  const advancedQuestions=(await db.query('SELECT v.payload FROM suizamente_private.sessions s JOIN suizamente_private.versions v ON v.id=ANY(s.version_ids) WHERE s.id=$1',[advanced.id])).rows.map(r=>r.payload)
  assert.ok(advancedQuestions.every(q=>q.difficulty>=4),'Do not substitute beginner cantonal items into an advanced route')
  assert.equal(advanced.fallback,true)
  console.log('Suizamente: all five ascents, per-category pass rules, daily limits and advanced cantonal fallback passed.')

  const snapshot=await szRpc(db,SZ_BOB,'start',{mode:'practice',category:'trabajo'})
  const admin=await szRpc(db,SZ_ADMIN,'admin')
  const original=admin.questions.find(q=>q.id===snapshot.question.id)
  await szRpc(db,SZ_ADMIN,'admin',{operation:'save_question',question:{...original.payload,prompt:'Pregunta actualizada para próximas partidas: '+original.payload.prompt}})
  const resumed=await szRpc(db,SZ_BOB,'session',{id:snapshot.id})
  assert.equal(resumed.question.prompt,snapshot.question.prompt,'Editing must not mutate an assigned question')
  const config=admin.config
  await assert.rejects(szRpc(db,SZ_ADMIN,'admin',{operation:'config',...config,thresholds:[150,100,800,1300,2000]}),/SZ_INVALID_CONFIG/)
  await assert.rejects(szRpc(db,SZ_ADMIN,'admin',{operation:'config',...config,xp_weights:[null,15,20,25,30]}),/SZ_INVALID_CONFIG/)
  await szRpc(db,SZ_ADMIN,'admin',{operation:'config',...config,xp_weights:[99,99,99,99,99]})
  const right=await szCorrectChoice(db,snapshot)
  const answered=await szRpc(db,SZ_BOB,'answer',{session_id:snapshot.id,position:0,choice:right})
  assert.equal(answered.answer.xp,config.xp_weights[snapshot.question.difficulty-1],'Started sessions keep their XP rules')
  await szRpc(db,SZ_BOB,'report',{version_id:snapshot.question.version_id,reason:'outdated',notes:'Revisar la redacción'})
  await szRpc(db,SZ_BOB,'report',{version_id:snapshot.question.version_id,reason:'outdated',notes:'Repeated request'})
  const report=(await szRpc(db,SZ_ADMIN,'admin')).reports.find(r=>r.version_id===snapshot.question.version_id)
  assert.ok(report)
  const unseenVersion=(await szRpc(db,SZ_ADMIN,'admin')).questions.find(q=>q.id===snapshot.question.id).version_id
  await assert.rejects(szRpc(db,SZ_ALICE,'report',{version_id:unseenVersion,reason:'incorrect'}),/SZ_REPORT_NOT_ALLOWED/)
  await szRpc(db,SZ_ADMIN,'admin',{operation:'resolve_report',id:report.id})
  const beforeRerun=(await db.query('SELECT count(*)::integer n FROM suizamente_private.versions')).rows[0].n
  await db.exec(await readFile('supabase/suizamente.sql','utf8'))
  await db.exec(await readFile('supabase/suizamente_seed.sql','utf8'))
  assert.equal((await db.query('SELECT count(*)::integer n FROM suizamente_private.versions')).rows[0].n,beforeRerun,'Re-running setup preserves editorial versions')
  await db.query('UPDATE profiles SET banned=true WHERE id=$1',[SZ_BOB])
  await assert.rejects(szRpc(db,SZ_BOB,'summary'),/SZ_ACCOUNT_UNAVAILABLE/)
  console.log('Suizamente: version snapshots, config validation, reports, bans and repeatable migrations passed.')

  const legacy=await createSuizamenteDb()
  try{
    let oldSession=await szRpc(legacy,SZ_ALICE,'start',{mode:'daily'})
    oldSession=await szRpc(legacy,SZ_ALICE,'answer',{session_id:oldSession.id,position:0,choice:await szCorrectChoice(legacy,oldSession)})
    const previousXp=(await szRpc(legacy,SZ_ALICE,'summary')).player.xp
    await legacy.exec('ALTER TABLE suizamente_private.answers DROP COLUMN skipped')
    await legacy.exec('ALTER TABLE suizamente_private.players DROP COLUMN include_general, DROP COLUMN include_canton')
    await legacy.exec("UPDATE suizamente_private.sessions SET rules=rules-'include_general'-'include_canton'")
    await legacy.exec(await readFile('supabase/suizamente.sql','utf8'))
    const upgraded=await szRpc(legacy,SZ_ALICE,'session',{id:oldSession.id})
    assert.equal(upgraded.answer.correct,true)
    assert.equal(upgraded.answer.skipped,false)
    assert.equal(upgraded.position,0)
    assert.equal((await szRpc(legacy,SZ_ALICE,'summary')).player.xp,previousXp)
    assert.equal((await szRpc(legacy,SZ_ALICE,'summary')).player.include_general,true)
    assert.equal((await szRpc(legacy,SZ_ALICE,'summary')).player.include_canton,true)
    assert.equal((await szRpc(legacy,SZ_ALICE,'start',{mode:'daily'})).id,oldSession.id)
    console.log('Suizamente: upgrading an existing answers table preserves confirmed choices, XP and active sessions.')

    const getScopes=async session=>(await legacy.query('SELECT v.payload FROM suizamente_private.sessions s JOIN suizamente_private.versions v ON v.id=ANY(s.version_ids) WHERE s.id=$1',[session.id])).rows.map(r=>r.payload)
    await szRpc(legacy,SZ_ALICE,'preferences',{canton:'ZH',alias:'AliceSources',include_general:true,include_canton:false})
    const generalOnly=await szRpc(legacy,SZ_ALICE,'start',{mode:'practice',category:'vivienda'})
    assert.ok((await getScopes(generalOnly)).every(q=>q.scope==='CH'))
    await assert.rejects(szRpc(legacy,SZ_ALICE,'preferences',{canton:'ZH',alias:'AliceSources',include_general:false,include_canton:false}),/SZ_NO_SOURCES/)
    assert.equal((await szRpc(legacy,SZ_ALICE,'summary')).player.include_general,true,'An invalid source update is atomic')
    await szRpc(legacy,SZ_ALICE,'preferences',{canton:'ZH',alias:'AliceSources',include_general:false,include_canton:true})
    let localOnly=await szRpc(legacy,SZ_ALICE,'start',{mode:'practice'})
    const localScopes=await getScopes(localOnly)
    assert.ok(localScopes.some(q=>q.scope==='canton'))
    assert.ok(localScopes.every(q=>q.scope==='CH'||q.canton==='ZH'))
    assert.equal(localOnly.fallback,true,'A short local bank is filled with general questions and explicitly flagged')
    await szRpc(legacy,SZ_ALICE,'preferences',{canton:'ZH',alias:'AliceSources',leaderboard_opt_in:true})
    assert.equal((await szRpc(legacy,SZ_ALICE,'summary')).player.include_general,false,'Ranking preferences preserve source preferences')
    const sameDaily=await szRpc(legacy,SZ_ALICE,'start',{mode:'daily'})
    assert.equal(sameDaily.id,oldSession.id)
    assert.equal(sameDaily.include_general,true,'An assigned daily route keeps its original source mix')
    localOnly=await finishSzSession(legacy,SZ_ALICE,localOnly)
    await legacy.query('UPDATE suizamente_private.players SET level=5 WHERE user_id=$1',[SZ_ALICE])
    const enoughLocal=await szRpc(legacy,SZ_ALICE,'start',{mode:'practice'})
    assert.ok((await getScopes(enoughLocal)).every(q=>q.scope==='canton'&&q.canton==='ZH'),'Only canton questions are used when enough eligible local content exists')
    assert.equal(enoughLocal.fallback,false)
    await szRpc(legacy,SZ_ALICE,'preferences',{canton:'ZH',alias:'AliceSources',include_general:true,include_canton:true})
    const mixedPractice=await szRpc(legacy,SZ_ALICE,'start',{mode:'practice',category:'vivienda'})
    assert.notEqual(mixedPractice.id,generalOnly.id,'A changed source selection starts a matching practice instead of resuming a different mix')
    await legacy.query("UPDATE auth.users SET raw_user_meta_data='{}' WHERE id=$1",[SZ_BOB])
    await legacy.query("UPDATE profiles SET canton='TI' WHERE id=$1",[SZ_BOB])
    assert.equal((await szRpc(legacy,SZ_BOB,'summary')).player.canton,'TI','Profile table canton is used if auth metadata has no canton')
    await assert.rejects(szRpc(legacy,SZ_ADMIN,'preferences',{canton:null,alias:'NoCanton',include_general:false,include_canton:true}),/SZ_CANTON_REQUIRED/)
    console.log('Suizamente: profile defaults, both/single sources, dropdown preferences, local fallback, snapshots and practice resume passed.')
  }finally{await legacy.close()}

  try {
    const bundles=await readdir('dist/assets')
    const text=(await Promise.all(bundles.filter(f=>f.endsWith('.js')).map(f=>readFile(`dist/assets/${f}`,'utf8')))).join('\n')
    for(const q of bank)assert.ok(!text.includes(q.id),`Private question ${q.id} leaked into browser bundle`)
    console.log('Suizamente: private question bank is absent from production bundles.')
  } catch(e){if(e.code!=='ENOENT')throw e}
} catch(e) {
  console.error('Suizamente test failed:',e.stack,e.where||'')
  process.exitCode=1
} finally { await db?.close() }
