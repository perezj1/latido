import assert from 'node:assert/strict'
import { readFile,writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import {isStatement} from '../src/lib/suizamenteQuestionText.js'

const source=new URL('../supabase/seed-data/suizamente-questions.json',import.meta.url)
const questions=JSON.parse(await readFile(source,'utf8'))
const ids=new Set(),categories=['administracion','vivienda','trabajo','salud','sociedad','idioma']
for(const q of questions){
  assert.match(q.id,/^[a-z0-9][a-z0-9_-]{2,100}$/)
  assert.ok(!ids.has(q.id),`Duplicate ID ${q.id}`);ids.add(q.id)
  assert.ok(categories.includes(q.category),q.id)
  if(q.game_type==='tf')assert.ok(isStatement(q.prompt),`${q.id}: true/false needs a statement`)
  assert.ok(Number.isInteger(q.difficulty)&&q.difficulty>=1&&q.difficulty<=5,q.id)
  assert.ok(q.game_type==='tf'?q.options.length===2:q.game_type==='multi'?q.options.length>=2&&q.options.length<=5:q.options.length===4,q.id)
  assert.equal(new Set(q.options.map(o=>o.trim().toLowerCase())).size,q.options.length,q.id)
  assert.ok(Number.isInteger(q.correct_index)&&q.correct_index>=0&&q.correct_index<q.options.length,q.id)
  if(q.game_type==='multi')assert.ok(q.correct_indices.length>0&&q.correct_indices.every(i=>Number.isInteger(i)&&i>=0&&i<q.options.length),q.id)
  if(q.game_type==='match')assert.equal(new Set(q.pairs).size,4,q.id)
  assert.equal(new URL(q.source_url).protocol,'https:',q.id)
  assert.ok(!JSON.stringify(q).includes('$sz_question$'),q.id)
}
const fingerprint=createHash('sha256').update(JSON.stringify(questions)).digest('hex')
const sql=[`-- Generated by npm run suizamente:seed. Private content, never import into the browser.`,
  `-- ${questions.length} questions. SHA-256: ${fingerprint}`,
  '-- Run AFTER supabase/suizamente.sql. Re-runs preserve existing editorial changes.',
  'BEGIN;',
  ...questions.map(q=>`SELECT suizamente_private.write_question($sz_question$${JSON.stringify(q)}$sz_question$::jsonb) WHERE NOT EXISTS (SELECT 1 FROM suizamente_private.questions WHERE id='${q.id}');`),
  "NOTIFY pgrst,'reload schema';",'COMMIT;',''].join('\n')
await writeFile(new URL('../supabase/suizamente_seed.sql',import.meta.url),sql,'utf8')
console.log(`Generated suizamente_seed.sql: ${questions.length} questions (${fingerprint.slice(0,12)}).`)
