import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { createFollowupTestDb, installFollowupSql, seedFollowup, TEST_CUSTOMER, TEST_OWNER, TEST_CONVERSATION } from './lib/followup-test-db.mjs'
const db = await createFollowupTestDb()
const scalar = async (sql, args = []) => Object.values((await db.query(sql, args)).rows[0])[0]
const claim = () => db.query('SELECT cf_claim_due(25) AS row')
const get = () => scalar('SELECT cf_get($1)', [TEST_CONVERSATION])
const answer = (round, value) => scalar('SELECT cf_answer($1,$2,$3)', [TEST_CONVERSATION, round, value])
try {
  await seedFollowup(db)
  await installFollowupSql(db)
  assert.equal(await scalar('SELECT count(*)::int FROM conversation_followups'), 1, 'Installing again preserves one followup')
  await db.exec('SET ROLE anon')
  await assert.rejects(get, /permission denied/)
  await assert.rejects(claim, /permission denied/)
  await db.exec('RESET ROLE; SET ROLE authenticated')
  await db.query("SELECT set_config('test.uid',$1,false)", [TEST_OWNER])
  assert.equal(await get(), null, 'Only the initiator sees the question')
  await assert.rejects(() => answer(1, 'yes'), /FORBIDDEN/)
  await assert.rejects(() => scalar('SELECT cf_admin_report()'), /FORBIDDEN/)
  await assert.rejects(() => db.query('SELECT * FROM conversation_followups'), /permission denied/)
  await db.query("SELECT set_config('test.uid',$1,false)", [TEST_CUSTOMER])
  const initial = await get()
  assert.equal(initial.due, true)
  assert.equal(initial.email_token, undefined)
  assert.equal(initial.outcome, 'pending')
  await assert.rejects(() => answer(1, 'maybe'), /INVALID_ANSWER/)
  await db.exec('RESET ROLE; SET ROLE service_role')
  const first = (await claim()).rows[0].row
  assert.equal(first.round, 1)
  assert.match(first.token, /^[a-f0-9]{64}$/)
  assert.equal((await claim()).rows.length, 0, 'A leased job cannot be claimed again')
  assert.equal((await scalar('SELECT cf_email_context($1)', [first.token])).due, true)
  await db.exec('RESET ROLE')
  assert.equal(await scalar('SELECT count(*)::int FROM app_notifications'), 1)
  await db.exec("UPDATE conversation_followups SET processing_at=now()-interval '11 minutes'")
  assert.equal((await claim()).rows[0].row.token, first.token, 'Retry retains a usable email link')
  assert.equal(await scalar('SELECT count(*)::int FROM app_notifications'), 1, 'No duplicate in-app notices')
  await db.exec('SET ROLE authenticated')
  const later = await answer(1, 'not_yet')
  assert.equal(later.round, 2)
  assert.equal(later.outcome, 'not_yet')
  assert.equal(later.due, false)
  assert.ok(Math.abs(new Date(later.due_at).getTime() - Date.now() - 7 * 86400000) < 5000)
  await assert.rejects(() => answer(1, 'not_yet'), /FOLLOWUP_CHANGED/)
  assert.equal((await answer(2, 'not_yet')).due_at, later.due_at, 'Selecting the same in-progress answer does not postpone the reminder')
  await db.exec('RESET ROLE; SET ROLE service_role')
  await assert.rejects(() => scalar('SELECT cf_answer_email($1,$2)', [first.token, 'yes']), /LINK_UNAVAILABLE/)
  assert.equal((await claim()).rows.length, 0, 'Nothing repeats before the next seven days')
  await db.exec("RESET ROLE; UPDATE conversation_followups SET due_at=now()-interval '1 second'")
  const second = (await claim()).rows[0].row
  assert.equal(second.round, 2)
  assert.notEqual(second.token, first.token)
  assert.equal(await scalar('SELECT count(*)::int FROM app_notifications'), 2)
  const yes = await scalar('SELECT cf_answer_email($1,$2)', [second.token, 'yes'])
  assert.equal(yes.outcome, 'yes')
  assert.equal(yes.due_at, null)
  assert.equal((await claim()).rows.length, 0, 'Yes ends reminders')
  assert.equal(await scalar("SELECT count(*)::int FROM app_notifications WHERE read_at IS NULL"), 0)
  const history = (await db.query('SELECT answer,channel FROM conversation_followup_answers ORDER BY answered_at')).rows
  assert.deepEqual(history, [{ answer: 'not_yet', channel: 'chat' }, { answer: 'yes', channel: 'email' }])
  await db.exec('SET ROLE authenticated')
  await db.query("SELECT set_config('test.admin','true',false)")
  const report = await scalar('SELECT cf_admin_report()')
  assert.equal(report.rows[0].outcome, 'yes')
  assert.equal(report.rows[0].last_channel, 'email')
  assert.equal(report.rows[0].email_token, undefined)
  assert.equal((await answer(3, 'not_yet')).outcome, 'not_yet', 'A confirmed answer can be changed')
  const dismissed = await scalar('SELECT cf_feedback($1,4,$2)', [TEST_CONVERSATION, 'dismiss'])
  assert.equal(dismissed.dismissed, true)
  assert.ok(dismissed.due_at, 'Closing an in-progress card keeps the reminder')
  await db.exec('RESET ROLE')
  await db.query("UPDATE conversation_followups SET due_at=now()-interval '1 second' WHERE conversation_id=$1", [TEST_CONVERSATION])
  await db.exec('SET ROLE authenticated')
  assert.equal((await get()).dismissed, false, 'The next due question is visible again')
  const negative = await answer(4, 'no')
  assert.equal(negative.reason_answered, false)
  assert.equal(negative.due_at, null)
  await assert.rejects(() => scalar('SELECT cf_feedback($1,5,$2,$3)', [TEST_CONVERSATION, 'reason', 'invalid']), /INVALID_REASON/)
  const reason = await scalar('SELECT cf_feedback($1,5,$2,$3)', [TEST_CONVERSATION, 'reason', 'not_replied'])
  assert.equal(reason.reason_answered, true)
  assert.equal(reason.no_reason, 'not_replied')
  assert.equal((await answer(5, 'yes')).no_reason, null, 'Changing the result clears the old reason')
  await db.exec('RESET ROLE')
  for (const channel of ['chat', 'email']) {
    const conversation = randomUUID()
    await db.query("INSERT INTO conversations(id,sender_id,owner_id,title) VALUES($1,$2,$3,'Consulta para cerrar')", [conversation, TEST_CUSTOMER, TEST_OWNER])
    await db.query("INSERT INTO messages(conversation_id,sender_id,body,created_at) VALUES($1,$2,'Consulta',now()-interval '8 days')", [conversation, TEST_CUSTOMER])
    let closed
    if (channel === 'chat') {
      await db.exec('SET ROLE authenticated')
      await scalar('SELECT cf_answer($1,1,$2)', [conversation, 'not_yet'])
      closed = await scalar('SELECT cf_answer($1,2,$2)', [conversation, 'no'])
      await db.exec('RESET ROLE')
    } else {
      const job = (await claim()).rows[0].row
      closed = await scalar('SELECT cf_answer_email($1,$2)', [job.token, 'no'])
      await assert.rejects(() => scalar('SELECT cf_email_context($1)', [job.token]), /LINK_UNAVAILABLE/)
      const explained = await scalar('SELECT cf_email_change($1,$2,$3,$4)', [closed.edit_token, closed.round, 'reason', 'not_match'])
      assert.equal(explained.no_reason, 'not_match')
      assert.equal(explained.reason_answered, true)
      assert.equal((await scalar('SELECT cf_email_change($1,$2,$3)', [explained.edit_token, explained.round, 'dismiss'])).dismissed, true)
      await db.query("UPDATE conversation_followups SET edit_expires_at=now()-interval '1 second' WHERE conversation_id=$1", [conversation])
      await assert.rejects(() => scalar('SELECT cf_email_change($1,$2,$3,$4)', [explained.edit_token, explained.round, 'answer', 'yes']), /LINK_UNAVAILABLE/)
    }
    assert.equal(closed.outcome, 'no')
    assert.equal(closed.due_at, null, 'No cancels the seven-day reminder')
    assert.equal(closed.due, false)
    assert.equal((await claim()).rows.length, 0, 'No ends both delivery channels')
  }
  await db.exec('SET ROLE authenticated')
  const negativeReport = await scalar("SELECT cf_admin_report('no')")
  assert.equal(negativeReport.total, 2)
  assert.equal(negativeReport.summary.no, 2)
  assert.equal(negativeReport.rows[0].email_token, undefined)
  assert.ok(negativeReport.rows.every(row => row.history.length > 0))
  await assert.rejects(() => scalar("SELECT cf_admin_report('invalid')"), /INVALID_FILTER/)
  await db.exec('RESET ROLE')
  const fresh = randomUUID()
  await db.query("INSERT INTO conversations(id,sender_id,owner_id,title) VALUES($1,$2,$3,'Consulta nueva')", [fresh, TEST_CUSTOMER, TEST_OWNER])
  await db.query("INSERT INTO messages(conversation_id,sender_id,body) VALUES($1,$2,'Primera consulta')", [fresh, TEST_CUSTOMER])
  await db.query("INSERT INTO messages(conversation_id,sender_id,body) VALUES($1,$2,'Segunda consulta')", [fresh, TEST_CUSTOMER])
  assert.equal(await scalar('SELECT count(*)::int FROM conversation_followups WHERE conversation_id=$1', [fresh]), 1)
  await db.exec('SET ROLE authenticated')
  assert.equal(await scalar('SELECT cf_get($1)', [fresh]), null, 'Question stays hidden in the first seven days')
  await db.exec('RESET ROLE')
  await db.query("UPDATE conversation_followups SET due_at=now()-interval '1 day' WHERE conversation_id=$1", [fresh])
  await db.query('UPDATE conversations SET deleted_by_sender=true WHERE id=$1', [fresh])
  assert.equal((await claim()).rows.length, 0, 'Deleted chats do not trigger reminders')
  await db.query('UPDATE conversations SET deleted_by_sender=false WHERE id=$1', [fresh])
  await db.query('UPDATE profiles SET banned=true WHERE id=$1', [TEST_CUSTOMER])
  assert.equal((await claim()).rows.length, 0, 'Blocked accounts do not trigger reminders')
  await db.query('UPDATE profiles SET banned=false WHERE id=$1', [TEST_CUSTOMER])
  const token = await scalar('SELECT email_token FROM conversation_followups WHERE conversation_id=$1', [fresh])
  await db.query("UPDATE conversation_followups SET token_expires_at=now()-interval '1 second' WHERE conversation_id=$1", [fresh])
  await assert.rejects(() => scalar('SELECT cf_email_context($1)', [token]), /LINK_UNAVAILABLE/)
  assert.equal((await claim()).rows.length, 0, 'Expired links are not emailed')
  const oldDb = await createFollowupTestDb({ install: false })
  try {
    await seedFollowup(oldDb)
    await installFollowupSql(oldDb)
    assert.equal(Object.values((await oldDb.query('SELECT count(*)::int FROM conversation_followups')).rows[0])[0], 0, 'Existing threads are not backfilled')
    await oldDb.query("INSERT INTO messages(conversation_id,sender_id,body) VALUES($1,$2,'Seguimos hablando')", [TEST_CONVERSATION, TEST_CUSTOMER])
    assert.equal(Object.values((await oldDb.query('SELECT count(*)::int FROM conversation_followups')).rows[0])[0], 0, 'A new message in an old thread does not launch a campaign')
  } finally { await oldDb.close() }
  await db.exec('SET ROLE authenticated')
  const beforeTestFilter = await scalar('SELECT cf_admin_report()')
  await db.exec('RESET ROLE')
  await db.query("UPDATE conversation_followups SET is_test=true,token_expires_at=now()+interval '37 days',due_at=now()-interval '1 minute',delivery_status='pending' WHERE conversation_id=$1", [fresh])
  assert.equal((await claim()).rows.length, 0, 'Operator fixtures never enter the real delivery queue')
  await db.exec('SET ROLE authenticated')
  const filteredReport = await scalar('SELECT cf_admin_report()')
  assert.equal(filteredReport.total, beforeTestFilter.total - 1)
  assert.equal(filteredReport.summary.total, beforeTestFilter.summary.total - 1)
  assert.equal(filteredReport.test_count, 1)
  assert.equal((await scalar("SELECT cf_admin_report('test')")).rows[0].conversation_id, fresh)
  console.log('Conversation followups: seven-day timing, ownership, RLS, retries, private tokens, email answers, history, admin summaries, isolated test fixtures and stopping after success passed.')
} finally { await db.close() }
