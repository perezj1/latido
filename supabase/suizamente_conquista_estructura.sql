 ('cincuenta','Pista 50/50',35,'Descarta dos respuestas incorrectas en una pregunta.'),
 ('segunda','Segunda oportunidad',50,'Puedes volver a responder la primera pregunta que falles.')
ON CONFLICT(codigo) DO UPDATE SET nombre=excluded.nombre,precio=excluded.precio,descripcion=excluded.descripcion;
CREATE TABLE IF NOT EXISTS suizamente_conquista.inventario(
 usuario uuid REFERENCES suizamente_conquista.billeteras ON DELETE CASCADE,
 ventaja text REFERENCES suizamente_conquista.ventajas,cantidad integer NOT NULL DEFAULT 0 CHECK(cantidad>=0),
 PRIMARY KEY(usuario,ventaja)
);
CREATE TABLE IF NOT EXISTS suizamente_conquista.territorios(
 usuario uuid REFERENCES suizamente_conquista.billeteras ON DELETE CASCADE,
 canton text REFERENCES suizamente_conquista.cantones,poseido boolean NOT NULL DEFAULT true,
 conquistado_en timestamptz NOT NULL DEFAULT now(),veces integer NOT NULL DEFAULT 1,
 defensas integer NOT NULL DEFAULT 0,victorias integer NOT NULL DEFAULT 0,
 PRIMARY KEY(usuario,canton)
);
CREATE TABLE IF NOT EXISTS suizamente_conquista.batallas(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),canton text NOT NULL REFERENCES suizamente_conquista.cantones,
 atacante uuid NOT NULL REFERENCES suizamente_conquista.billeteras ON DELETE CASCADE,
 defensor uuid NOT NULL REFERENCES suizamente_conquista.billeteras ON DELETE CASCADE,
 estado text NOT NULL DEFAULT 'pendiente' CHECK(estado IN('pendiente','activa','terminada','rechazada','caducada')),
 apuesta integer NOT NULL DEFAULT 100 CHECK(apuesta=100),ventajas_atacante text[] NOT NULL DEFAULT '{}',
 ventajas_defensor text[] NOT NULL DEFAULT '{}',preguntas text[],ganador uuid,
 motivo text,creado_en timestamptz NOT NULL DEFAULT now(),aceptado_en timestamptz,
 vence_en timestamptz NOT NULL DEFAULT now()+interval '24 hours',terminado_en timestamptz,
 CHECK(atacante<>defensor)
);
CREATE UNIQUE INDEX IF NOT EXISTS cq_disputa_unica ON suizamente_conquista.batallas(defensor,canton) WHERE estado IN('pendiente','activa');
CREATE UNIQUE INDEX IF NOT EXISTS cq_ataque_unico ON suizamente_conquista.batallas(atacante,canton) WHERE estado IN('pendiente','activa');
CREATE TABLE IF NOT EXISTS suizamente_conquista.partidas(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),usuario uuid NOT NULL REFERENCES suizamente_conquista.billeteras ON DELETE CASCADE,
 canton text NOT NULL REFERENCES suizamente_conquista.cantones,
