CREATE SCHEMA IF NOT EXISTS suizamente_conquista;
REVOKE ALL ON SCHEMA suizamente_conquista FROM PUBLIC,anon,authenticated;

CREATE TABLE IF NOT EXISTS suizamente_conquista.cantones(
 codigo text PRIMARY KEY REFERENCES suizamente_social.cantones,
 nivel text NOT NULL CHECK(nivel IN('facil','medio','dificil')),
 coste integer NOT NULL CHECK(coste>0),cantidad integer NOT NULL CHECK(cantidad IN(5,7,10))
);
CREATE TABLE IF NOT EXISTS suizamente_conquista.preguntas(
 id text PRIMARY KEY,canton text NOT NULL REFERENCES suizamente_conquista.cantones,
 tema text NOT NULL,pregunta text NOT NULL,opciones jsonb NOT NULL CHECK(jsonb_array_length(opciones)=4),
 correcta integer NOT NULL CHECK(correcta BETWEEN 0 AND 3),explicacion text NOT NULL,
 fuente text NOT NULL CHECK(fuente LIKE 'https://%'),revisada date NOT NULL,activa boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS suizamente_conquista.billeteras(
 usuario uuid PRIMARY KEY REFERENCES suizamente_social.jugadores(usuario_id) ON DELETE CASCADE,
 saldo integer NOT NULL DEFAULT 0 CHECK(saldo>=0),xp_acreditada integer NOT NULL DEFAULT 0,
 competitivo boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS suizamente_conquista.movimientos(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario uuid NOT NULL REFERENCES suizamente_conquista.billeteras ON DELETE CASCADE,
 cantidad integer NOT NULL,concepto text NOT NULL,referencia text NOT NULL,
 creado_en timestamptz NOT NULL DEFAULT now(),UNIQUE(usuario,concepto,referencia)
);
CREATE TABLE IF NOT EXISTS suizamente_conquista.ventajas(
 codigo text PRIMARY KEY,nombre text NOT NULL,precio integer NOT NULL CHECK(precio>0),descripcion text NOT NULL
);
